#!/usr/bin/env python3
"""从数值手册数据生成 src/Generated/ClientTables.cs（identifier -> 卖什么 / 买什么 的中文说明）。

data/clients.json 与 data/player/clients.json 是同一批 367 个客户工厂方法、同一顺序，
前者有 identifier，后者有面向玩家的中文 sells/buys 文本。按下标对齐。

用法: python3 -I tools/gen_client_tables.py <ProbablyStolen 项目根> <输出 .cs>
"""
import json
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])
dev = json.loads((root / "data/clients.json").read_text(encoding="utf-8"))["clients"]
player = json.loads((root / "data/player/clients.json").read_text(encoding="utf-8"))["clients"]
assert len(dev) == len(player), (len(dev), len(player))

ID_RE = re.compile(r"^[A-Za-z0-9_]+$")
sells, buys = {}, {}
for d, p in zip(dev, player):
    ids = [d.get("identifier")] + list(d.get("dict_ids") or [])
    ids = [i for i in ids if i and ID_RE.match(i) and not i.startswith("debug")]
    for key, table in (("sells", sells), ("buys", buys)):
        text = (p.get(key) or "").strip()
        if not text:
            continue
        text = re.sub(r"\\\(|\\\)|\\text\{([^}]*)\}", lambda m: m.group(1) or "", text)
        text = re.sub(r"\s+", " ", text)
        for i in ids:
            table.setdefault(i, text)


def cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "// <auto-generated> 由 tools/gen_client_tables.py 从 data/clients.json + data/player/clients.json 生成，请勿手改。",
    "using System.Collections.Generic;",
    "",
    "namespace VisitorForecast.Forecast",
    "{",
    "    internal static class ClientTables",
    "    {",
]
for name, table in (("Sells", sells), ("Buys", buys)):
    lines.append(f"        internal static readonly Dictionary<string, string> {name} = new Dictionary<string, string>")
    lines.append("        {")
    for k in sorted(table):
        lines.append(f"            {{ {cs(k)}, {cs(table[k])} }},")
    lines.append("        };")
    lines.append("")
lines += ["    }", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"sells={len(sells)} buys={len(buys)} -> {out}")
